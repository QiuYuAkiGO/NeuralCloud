"""Durable production memory: immutable evidence, revisable beliefs, scoped recall.

Identity is global within one owner; permission is always attached to evidence.
The store never treats remembering, model repetition or internal feelings as new
external evidence. Old interpretation payloads remain available for migration
and audit, rather than being regenerated by a model.
"""
from __future__ import annotations

from contextlib import closing
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import sqlite3
from typing import Literal

from pydantic import AwareDatetime, BaseModel, ConfigDict, Field, model_validator

from harness.core.models import MemoryScope


def _json(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False)


def _hash(value):
    return hashlib.sha256(_json(value).encode()).hexdigest()


def _time(value=None):
    value = value or datetime.now(timezone.utc)
    if value.utcoffset() is None:
        raise ValueError("memory time must have a timezone")
    return value.astimezone(timezone.utc).isoformat()


def _terms(text):
    words = set(re.findall(r"[a-z0-9_]+", text.casefold()))
    for run in re.findall(r"[\u3400-\u9fff]+", text):
        words.update(run[i:i + 2] for i in range(max(1, len(run) - 1)))
    return sorted(words)[:256]


class Experience(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True, revalidate_instances="always")
    record_id: str = Field(min_length=1)
    author_id: str = Field(min_length=1)
    text: str = Field(min_length=1)
    occurred_at: AwareDatetime
    scope: MemoryScope
    source_refs: tuple[str, ...] = ()
    independent_key: str = Field(min_length=1)
    kind: Literal["observation", "self_expression", "legacy_episode"] = "observation"
    original: dict = Field(default_factory=dict)

    @model_validator(mode="after")
    def evidence_identity(self):
        if self.kind != "legacy_episode" and not self.source_refs:
            raise ValueError("source_experience_requires_original_references")
        return self


class BeliefRevision(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True, revalidate_instances="always")
    record_id: str = Field(min_length=1)
    subject_id: str = Field(min_length=1)
    topic: str = Field(min_length=1)
    context: str = ""
    statement: str = Field(min_length=1)
    kind: Literal["interpretation", "self_report", "legacy_interpretation"] = "interpretation"
    revision: int = Field(ge=1)
    supporting_ids: tuple[str, ...] = Field(default=(), max_length=128)
    counter_ids: tuple[str, ...] = Field(default=(), max_length=128)
    valid_from: AwareDatetime
    valid_until: AwareDatetime | None = None
    supersedes: tuple[str, ...] = ()
    original: dict = Field(default_factory=dict)

    @model_validator(mode="after")
    def valid_evidence(self):
        combined = self.supporting_ids + self.counter_ids
        if not combined or len(set(combined)) != len(combined):
            raise ValueError("belief requires unique, disjoint supporting/counter evidence")
        if self.valid_until and self.valid_until <= self.valid_from:
            raise ValueError("belief validity interval must be nonempty")
        return self


class ProductionMemoryStore:
    """One SQLite authority per owner/preset, with atomic cursors and receipts."""

    def __init__(self, path, *, owner_id="misty", preset_id="misty"):
        self.path = Path(path)
        self.owner_id, self.preset_id = owner_id, preset_id
        self.path.parent.mkdir(parents=True, exist_ok=True)
        with closing(self._connect()) as db, db:
            had_postings = db.execute("SELECT 1 FROM sqlite_master WHERE type='table' AND name='pm_postings'").fetchone()
            had_source_identity = db.execute("SELECT 1 FROM sqlite_master WHERE type='table' AND name='pm_source_identity'").fetchone()
            had_lineage = db.execute("SELECT 1 FROM sqlite_master WHERE type='table' AND name='pm_legacy_valid'").fetchone()
            had_evidence_revision = db.execute("SELECT 1 FROM sqlite_master WHERE type='table' AND name='pm_evidence_revision'").fetchone()
            db.executescript("""
                CREATE TABLE IF NOT EXISTS pm_identity(singleton INTEGER PRIMARY KEY, owner TEXT, preset TEXT);
                CREATE TABLE IF NOT EXISTS pm_sources(id TEXT PRIMARY KEY, author TEXT, time TEXT, payload TEXT, digest TEXT, revoked INTEGER NOT NULL DEFAULT 0);
                CREATE TABLE IF NOT EXISTS pm_source_alias(alias TEXT, id TEXT, PRIMARY KEY(alias,id));
                CREATE TABLE IF NOT EXISTS pm_independent(key TEXT PRIMARY KEY, author TEXT, text_hash TEXT);
                CREATE TABLE IF NOT EXISTS pm_source_identity(key TEXT,id TEXT,PRIMARY KEY(key,id));
                CREATE INDEX IF NOT EXISTS pm_source_identity_id ON pm_source_identity(id);
                CREATE TABLE IF NOT EXISTS pm_source_original(ref TEXT,id TEXT,PRIMARY KEY(ref,id));
                CREATE INDEX IF NOT EXISTS pm_source_original_id ON pm_source_original(id);
                CREATE TABLE IF NOT EXISTS pm_legacy_dependencies(id TEXT,ref TEXT,PRIMARY KEY(id,ref));
                CREATE INDEX IF NOT EXISTS pm_legacy_dependencies_ref ON pm_legacy_dependencies(ref);
                CREATE TABLE IF NOT EXISTS pm_lineage(parent TEXT,child TEXT,PRIMARY KEY(parent,child));
                CREATE INDEX IF NOT EXISTS pm_lineage_child ON pm_lineage(child);
                CREATE TABLE IF NOT EXISTS pm_legacy_valid(id TEXT PRIMARY KEY,complete INTEGER NOT NULL DEFAULT 0);
                CREATE TABLE IF NOT EXISTS pm_revisions(id TEXT, revision INTEGER, payload TEXT, PRIMARY KEY(id,revision));
                CREATE TABLE IF NOT EXISTS pm_records(id TEXT PRIMARY KEY, kind TEXT, subject TEXT, text TEXT, time TEXT, revision INTEGER NOT NULL DEFAULT 0, active INTEGER NOT NULL DEFAULT 1, confidence REAL, pinned INTEGER NOT NULL DEFAULT 0, important INTEGER NOT NULL DEFAULT 0);
                CREATE TABLE IF NOT EXISTS pm_visibility(id TEXT, audience TEXT, PRIMARY KEY(audience,id));
                CREATE INDEX IF NOT EXISTS pm_visibility_id ON pm_visibility(id);
                CREATE TABLE IF NOT EXISTS pm_terms(term TEXT, id TEXT, PRIMARY KEY(term,id));
                CREATE INDEX IF NOT EXISTS pm_terms_id ON pm_terms(id);
                CREATE TABLE IF NOT EXISTS pm_postings(audience TEXT,term TEXT,id TEXT,time TEXT,priority INTEGER,PRIMARY KEY(audience,term,id));
                CREATE INDEX IF NOT EXISTS pm_postings_recent ON pm_postings(audience,term,priority DESC,time DESC,id);
                CREATE INDEX IF NOT EXISTS pm_postings_id ON pm_postings(id);
                CREATE TABLE IF NOT EXISTS pm_evidence(id TEXT, source TEXT, stance TEXT, PRIMARY KEY(id,source));
                CREATE INDEX IF NOT EXISTS pm_evidence_source ON pm_evidence(source,id);
                CREATE TABLE IF NOT EXISTS pm_evidence_revision(id TEXT,source TEXT,revision INTEGER,PRIMARY KEY(id,source));
                CREATE INDEX IF NOT EXISTS pm_subject ON pm_records(subject,active,time);
                CREATE INDEX IF NOT EXISTS pm_recent ON pm_records(active,time DESC);
                CREATE INDEX IF NOT EXISTS pm_belief_recent ON pm_records(time DESC,id) WHERE kind='belief' AND active=1;
                CREATE INDEX IF NOT EXISTS pm_person_recent ON pm_records(time DESC,id) WHERE kind IN ('belief','claim_v2') AND active=1;
                CREATE TABLE IF NOT EXISTS pm_receipts(event_id TEXT PRIMARY KEY, kind TEXT, digest TEXT, payload TEXT);
                CREATE TABLE IF NOT EXISTS pm_cursors(stream TEXT PRIMARY KEY, cursor INTEGER NOT NULL);
                CREATE TABLE IF NOT EXISTS pm_legacy(id TEXT PRIMARY KEY, digest TEXT, payload TEXT);
                CREATE TABLE IF NOT EXISTS pm_legacy_versions(id TEXT, digest TEXT, payload TEXT, PRIMARY KEY(id,digest));
                CREATE TABLE IF NOT EXISTS pm_legacy_presence(id TEXT PRIMARY KEY,present INTEGER NOT NULL);
                CREATE TABLE IF NOT EXISTS pm_retention(id TEXT PRIMARY KEY, reason TEXT, evidence TEXT);
            """)
            db.execute("INSERT OR IGNORE INTO pm_identity VALUES(1,?,?)", (owner_id, preset_id))
            identity = db.execute("SELECT owner,preset FROM pm_identity WHERE singleton=1").fetchone()
            if tuple(identity) != (owner_id, preset_id):
                raise ValueError("production_memory_owner_mismatch")
            if not had_evidence_revision:
                db.execute("""INSERT OR IGNORE INTO pm_evidence_revision
                    SELECT e.id,e.source,r.revision FROM pm_evidence e JOIN pm_records r ON r.id=e.source""")
            if not had_postings:
                db.execute("""INSERT OR IGNORE INTO pm_postings
                    SELECT v.audience,t.term,t.id,r.time,r.pinned+r.important FROM pm_terms t
                    JOIN pm_visibility v ON v.id=t.id JOIN pm_records r ON r.id=t.id""")
            if not had_source_identity:
                db.execute("""INSERT OR IGNORE INTO pm_source_identity
                    SELECT json_extract(payload,'$.independent_key'),id FROM pm_sources""")
            if not had_lineage:
                # One-time schema migration, never a foreground recall scan.
                db.execute("""INSERT OR IGNORE INTO pm_source_original SELECT id,id FROM pm_sources
                    WHERE json_extract(payload,'$.kind')<>'legacy_episode'""")
                db.execute("""INSERT OR IGNORE INTO pm_source_original
                    SELECT json_extract(payload,'$.source_refs[0]'),id FROM pm_sources
                    WHERE json_type(payload,'$.original.record')='object'
                      AND json_extract(payload,'$.kind')<>'legacy_episode'""")
                db.execute("""INSERT OR IGNORE INTO pm_legacy_valid SELECT id,0 FROM pm_sources
                    WHERE json_extract(payload,'$.kind')='legacy_episode'""")
                db.execute("""INSERT OR IGNORE INTO pm_legacy_dependencies
                    SELECT s.id,refs.value FROM pm_sources s,json_each(s.payload,'$.source_refs') refs
                    WHERE json_extract(s.payload,'$.kind')='legacy_episode'""")
                for row in db.execute("SELECT id FROM pm_legacy_valid").fetchall():
                    self._refresh_legacy_lineage(db, row[0])
            from harness.memory.evidence_v2 import ensure_schema
            ensure_schema(db)

    def _connect(self):
        db = sqlite3.connect(self.path, timeout=5)
        db.row_factory = sqlite3.Row
        db.execute("PRAGMA foreign_keys=ON")
        return db

    @staticmethod
    def _receipt(db, event_id, kind, payload):
        digest = _hash(payload)
        row = db.execute("SELECT kind,digest FROM pm_receipts WHERE event_id=?", (event_id,)).fetchone()
        if row:
            if (row["kind"], row["digest"]) != (kind, digest):
                raise ValueError("memory_receipt_identity_conflict")
            return False
        db.execute("INSERT INTO pm_receipts VALUES(?,?,?,?)", (event_id, kind, digest, _json(payload)))
        return True

    @staticmethod
    def _index(db, identifier, text, visibility):
        db.execute("DELETE FROM pm_terms WHERE id=?", (identifier,))
        db.execute("DELETE FROM pm_visibility WHERE id=?", (identifier,))
        db.execute("DELETE FROM pm_postings WHERE id=?", (identifier,))
        db.executemany("INSERT INTO pm_terms VALUES(?,?)", ((term, identifier) for term in _terms(text)))
        db.executemany("INSERT INTO pm_visibility VALUES(?,?)", ((identifier, audience) for audience in sorted(set(visibility))))
        row = db.execute("SELECT time,pinned+important AS priority FROM pm_records WHERE id=?", (identifier,)).fetchone()
        db.executemany("INSERT INTO pm_postings VALUES(?,?,?,?,?)",
                       ((audience, term, identifier, row["time"], row["priority"]) for audience in sorted(set(visibility)) for term in _terms(text)))

    def _ingest(self, db, experience):
        experience = Experience.model_validate(experience)
        experience = Experience.model_validate_json(experience.model_dump_json())
        if experience.scope.owner_id != self.owner_id:
            raise ValueError("experience_owner_mismatch")
        raw = experience.model_dump(mode="json")
        row = db.execute("SELECT digest FROM pm_sources WHERE id=?", (experience.record_id,)).fetchone()
        if row:
            if row[0] != _hash(raw):
                raise ValueError("immutable_experience_changed")
            return False
        if experience.kind != "legacy_episode":
            independent = db.execute("SELECT author,text_hash FROM pm_independent WHERE key=?", (experience.independent_key,)).fetchone()
            binding = (experience.author_id, _hash(experience.text))
            if independent and tuple(independent) != binding:
                raise ValueError("independent_source_identity_conflict")
            db.execute("INSERT OR IGNORE INTO pm_independent VALUES(?,?,?)", (experience.independent_key, *binding))
        revoked = db.execute("""SELECT 1 FROM pm_source_identity i JOIN pm_sources s ON s.id=i.id
            WHERE i.key=? AND s.revoked=1 LIMIT 1""", (experience.independent_key,)).fetchone() is not None
        db.execute("INSERT INTO pm_sources VALUES(?,?,?,?,?,?)",
                   (experience.record_id, experience.author_id, _time(experience.occurred_at), _json(raw), _hash(raw), int(revoked)))
        db.execute("INSERT OR IGNORE INTO pm_source_identity VALUES(?,?)", (experience.independent_key, experience.record_id))
        db.executemany("INSERT OR IGNORE INTO pm_source_alias VALUES(?,?)",
                       ((ref, experience.record_id) for ref in experience.source_refs))
        db.execute("INSERT INTO pm_records(id,kind,subject,text,time) VALUES(?,?,?,?,?)",
                   (experience.record_id, "experience", experience.author_id, experience.text, _time(experience.occurred_at)))
        if revoked:
            db.execute("UPDATE pm_records SET active=0 WHERE id=?", (experience.record_id,))
        record = experience.original.get("record", {})
        if (record.get("session_id") == "operator-confirmed-facts" and record.get("kind") == "local_incoming"
                and experience.author_id == "local:main" and "local:main" in experience.scope.visibility):
            db.execute("UPDATE pm_records SET pinned=1 WHERE id=?", (experience.record_id,))
            db.execute("INSERT OR IGNORE INTO pm_retention VALUES(?,?,?)", (experience.record_id,
                "explicit_operator_confirmation", _json([experience.record_id])))
        self._index(db, experience.record_id, experience.text, experience.scope.visibility)
        if experience.kind == "legacy_episode":
            db.execute("INSERT OR IGNORE INTO pm_legacy_valid VALUES(?,0)", (experience.record_id,))
            db.executemany("INSERT OR IGNORE INTO pm_legacy_dependencies VALUES(?,?)",
                           ((experience.record_id, ref) for ref in experience.source_refs))
            self._refresh_legacy_lineage(db, experience.record_id)
        else:
            originals = {experience.record_id}
            if isinstance(experience.original.get("record"), dict):
                originals.add(experience.source_refs[0])
            for ref in originals:
                db.execute("INSERT OR IGNORE INTO pm_source_original VALUES(?,?)", (ref, experience.record_id))
                for legacy in db.execute("SELECT id FROM pm_legacy_dependencies WHERE ref=?", (ref,)).fetchall():
                    self._refresh_legacy_lineage(db, legacy[0])
        return True

    @staticmethod
    def _deactivate_source_tree(db, source_ids):
        pending, visited = list(source_ids), set()
        while pending:
            identifier = pending.pop()
            if identifier in visited:
                continue
            visited.add(identifier)
            pending.extend(row[0] for row in db.execute("SELECT child FROM pm_lineage WHERE parent=?", (identifier,)))
            db.execute("UPDATE pm_sources SET revoked=1 WHERE id=?", (identifier,))
            db.execute("UPDATE pm_records SET active=0 WHERE id=? OR id IN (SELECT id FROM pm_evidence WHERE source=?)",
                       (identifier, identifier))

    @classmethod
    def _refresh_legacy_lineage(cls, db, identifier):
        """Link exact original IDs only; ambiguous/missing references fail closed."""
        refs = [row[0] for row in db.execute("SELECT ref FROM pm_legacy_dependencies WHERE id=?", (identifier,))]
        legacy = cls._effective_source(db, db.execute("SELECT payload FROM pm_sources WHERE id=?", (identifier,)).fetchone()[0])
        complete, revoked, parents = bool(refs), False, set()
        for ref in refs:
            sources = db.execute("""SELECT s.id,s.payload,s.revoked FROM pm_source_original o
                JOIN pm_sources s ON s.id=o.id WHERE o.ref=?""", (ref,)).fetchall()
            if not sources:
                complete = False
                continue
            candidates = [(row, Experience.model_validate_json(row["payload"])) for row in sources]
            # Duplicate captures of one exact event are equivalent; two distinct
            # original events with the same alias are ambiguous, never guessed.
            if len({item.independent_key for _, item in candidates}) != 1:
                complete = False
                continue
            if any(not set(legacy.scope.visibility).issubset(item.scope.visibility) for _, item in candidates):
                complete = False
                continue
            parents.update(row["id"] for row, _ in candidates)
            revoked |= any(bool(row["revoked"]) for row, _ in candidates)
        db.execute("DELETE FROM pm_lineage WHERE child=?", (identifier,))
        db.executemany("INSERT OR IGNORE INTO pm_lineage VALUES(?,?)", ((parent, identifier) for parent in parents))
        db.execute("UPDATE pm_legacy_valid SET complete=? WHERE id=?", (int(complete), identifier))
        if revoked:
            cls._deactivate_source_tree(db, [identifier])

    @staticmethod
    def _effective_source(db, payload):
        """Legacy summaries are current interpretations over immutable history."""
        source = Experience.model_validate_json(payload)
        if source.kind != "legacy_episode":
            return source
        row = db.execute("SELECT payload FROM pm_legacy WHERE id=?", (source.record_id,)).fetchone()
        if row is None:
            return source
        from harness.core.models import EpisodicEvent
        event = EpisodicEvent.model_validate_json(row[0])
        return source.model_copy(update={"text": event.objective_fact or event.summary,
            "scope": event.scope or MemoryScope(channel=event.channel, conversation_id=event.session_id),
            "source_refs": tuple(event.source_refs), "occurred_at": event.time})

    @staticmethod
    def _evidence_versions_current(db, identifier):
        return db.execute("""SELECT 1 FROM pm_evidence_revision e LEFT JOIN pm_records r ON r.id=e.source
            LEFT JOIN pm_legacy_presence p ON p.id=e.source WHERE e.id=?
            AND (r.id IS NULL OR r.revision<>e.revision OR p.present=0) LIMIT 1""", (identifier,)).fetchone() is None

    def ingest(self, experiences, *, stream=None, cursor=None):
        """Commit a source batch and its monotonic ingestion cursor together."""
        if (stream is None) != (cursor is None) or (cursor is not None and (type(cursor) is not int or cursor < 0)):
            raise ValueError("source cursor needs a stream and nonnegative integer")
        with closing(self._connect()) as db, db:
            db.execute("BEGIN IMMEDIATE")
            count = sum(self._ingest(db, item) for item in experiences)
            if stream is not None:
                previous = db.execute("SELECT cursor FROM pm_cursors WHERE stream=?", (stream,)).fetchone()
                if previous and cursor < previous[0]:
                    raise ValueError("source_cursor_moved_backwards")
                db.execute("INSERT INTO pm_cursors VALUES(?,?) ON CONFLICT(stream) DO UPDATE SET cursor=excluded.cursor", (stream, cursor))
            return count

    def cursor(self, stream):
        with closing(self._connect()) as db:
            row = db.execute("SELECT cursor FROM pm_cursors WHERE stream=?", (stream,)).fetchone()
            return row[0] if row else 0

    @staticmethod
    def from_shared(record):
        original = json.loads(record.source.original_json)
        key = ("qq-message:" + _hash([record.session_id, record.author_principal, original["message_id"]])
               if record.kind == "qq_observation" and original.get("message_id") else record.source.original_record_id)
        return Experience(record_id=record.record_id, author_id=record.author_principal,
            text=record.text or "[资料观察]", occurred_at=record.occurred_at,
            scope=MemoryScope(owner_id=record.owner_id, channel=record.channel,
                              conversation_id=record.session_id, visibility=list(record.visibility)),
            source_refs=tuple(dict.fromkeys((record.source.original_record_id, *record.evidence_refs))),
            independent_key=key,
            kind="self_expression" if record.author_principal.startswith("character:") else "observation",
            original={"record": record.model_dump(mode="json", exclude={"stored_at", "source"}),
                      "source": original})

    def ingest_local(self, event):
        """Accept a channel-authenticated SharedLocalEvent, not model text."""
        from harness.memory.shared import SharedLocalEvent, SharedMemoryStore
        event = SharedLocalEvent.model_validate(event)
        shared = SharedMemoryStore(self.path, owner_id=self.owner_id, preset_id=self.preset_id)
        record = shared._prepare("local_incoming" if event.role == "user" else "local_outgoing",
                                 event.event_id, event, event.visibility)
        self.ingest([self.from_shared(record)])
        return record.record_id

    @staticmethod
    def _prepare_qq_original(shared, kind, item, audience, memory_db=None):
        """Keep old raw field sets while checking the trusted adapter's DTO."""
        original_json = None
        if memory_db is not None:
            table = "qq_visual_profiles" if kind == "qq_profile" else "qq_visual_observations"
            with closing(sqlite3.connect(Path(memory_db).resolve().as_uri() + "?mode=ro", uri=True)) as db:
                row = db.execute(f"SELECT group_id,record_json FROM {table} WHERE record_id=?", (item.record_id,)).fetchone()
            if (row is None or row[0] != item.group_id
                    or type(item).model_validate_json(row[1]).model_dump(mode="json") != item.model_dump(mode="json")):
                raise ValueError("qq_raw_source_changed")
            original_json = row[1]
        return shared._prepare(kind, item.record_id, item, ("local:main", audience), original_row_json=original_json)

    def ingest_qq(self, observation, *, memory_db=None):
        """Accept a provider-verified QQ observation with its stable account ID."""
        from harness.memory.shared import SharedMemoryStore
        from harness.qq.memory import QQVisualObservation
        from harness.qq.conversation import conversation_audience
        observation = QQVisualObservation.model_validate(observation)
        shared = SharedMemoryStore(self.path, owner_id=self.owner_id, preset_id=self.preset_id)
        record = self._prepare_qq_original(shared, "qq_observation", observation,
            conversation_audience(observation.group_id), memory_db)
        self.ingest([self.from_shared(record)])
        return record.record_id

    def filter_qq_context(self, context, *, memory_db=None):
        """Filter trusted raw QQ history against the same source tombstones.

        Retrieval from the immutable QQ archive is not itself a permission to
        show withdrawn history. Profiles and observations are both exact IDs.
        """
        from harness.memory.shared import SharedMemoryStore
        from harness.qq.conversation import conversation_audience
        audience = conversation_audience(context.group_id)
        shared = SharedMemoryStore(self.path, owner_id=self.owner_id, preset_id=self.preset_id)
        records = []
        canonical = {}
        for member in context.members:
            for kind, items in (("qq_profile", member.profiles), ("qq_observation", member.observations)):
                for item in items:
                    if item.group_id != context.group_id:
                        raise ValueError("qq_raw_source_scope_mismatch")
                    record = self._prepare_qq_original(shared, kind, item, audience, memory_db)
                    records.append(self.from_shared(record))
                    canonical[item.record_id] = record.record_id
        self.ingest(records)
        with closing(self._connect()) as db:
            allowed = {original for original, identifier in canonical.items() if self._visible(db, identifier, audience)}
        members = []
        for member in context.members:
            profiles = [item for item in member.profiles if item.record_id in allowed]
            profile_ids = {item.record_id for item in profiles}
            observations = [item for item in member.observations
                            if item.record_id in allowed and item.profile_record_id in profile_ids]
            if profiles:
                members.append(member.model_copy(update={"profiles": profiles, "observations": observations}))
        kept = {item.record_id for member in members for item in member.observations}
        retrieval = []
        for item in context.member_retrieval:
            if item.member_id not in {member.member_id for member in members}:
                continue
            retrieval.append(item.model_copy(update={
                "recent_record_ids": [ref for ref in item.recent_record_ids if ref in kept],
                "history_record_ids": [ref for ref in item.history_record_ids if ref in kept],
                "history_matches": [match for match in item.history_matches if match.record_id in kept]}))
        return context.model_copy(update={"members": members, "participants": [member.member_id for member in members],
                                          "member_retrieval": retrieval})

    def original_references(self, original_ids, *, audience):
        """Resolve explicit original IDs for a frozen QQ selection, fail closed."""
        references = []
        with closing(self._connect()) as db:
            for original in dict.fromkeys(original_ids):
                rows = db.execute("SELECT id FROM pm_source_original WHERE ref=?", (original,)).fetchall()
                if len(rows) != 1 or not self._visible(db, rows[0][0], audience):
                    raise ValueError("production_original_source_unavailable")
                references.append({"record_id": rows[0][0], "revision": 0})
        return references

    def sync_shared(self, shared, *, batch_size=256):
        """Bounded catch-up. No full archive mirror in the caller's request path."""
        stream = "shared:" + str(shared.path.absolute())
        page = shared.read_after(cursor=self.cursor(stream), limit=batch_size)
        self.ingest([self.from_shared(record) for record in page.records], stream=stream, cursor=page.next_cursor)
        return page

    @staticmethod
    def _resolve_source(db, ref, audience):
        direct = db.execute("SELECT id FROM pm_sources WHERE id=? AND revoked=0", (ref,)).fetchone()
        identifiers = [direct[0]] if direct else [r[0] for r in db.execute(
            "SELECT s.id FROM pm_source_alias a JOIN pm_sources s ON s.id=a.id WHERE a.alias=? AND s.revoked=0", (ref,))]
        visible = [identifier for identifier in identifiers if db.execute(
            "SELECT 1 FROM pm_visibility WHERE id=? AND audience=?", (identifier, audience)).fetchone()]
        if len(visible) != 1:
            raise ValueError("memory_source_missing_ambiguous_or_private")
        return visible[0]

    def apply_updates(self, updates, *, event_id, audience, subject_id, now=None):
        """Apply a frozen model proposal using only authenticated visible sources.

        ``subject_id`` and ``audience`` come from the channel, not the model.
        A retry of the same turn cannot create another interpretation revision.
        """
        if len(updates) > 16:
            raise ValueError("too_many_memory_updates")
        moment = now or datetime.now(timezone.utc)
        payload = {"updates": updates, "audience": audience, "subject_id": subject_id}
        with closing(self._connect()) as db, db:
            db.execute("BEGIN IMMEDIATE")
            if not self._receipt(db, event_id, "model_updates", payload):
                return False
            for index, update in enumerate(updates):
                kind = update.get("kind")
                supports = tuple(dict.fromkeys(self._resolve_source(db, ref, audience) for ref in update.get("source_ids", [])))
                counters = tuple(dict.fromkeys(self._resolve_source(db, ref, audience) for ref in update.get("counter_ids", [])))
                # The legacy contract requires disjoint source roles. Check
                # canonical identities before existing-history merge can
                # silently remove an overlap from one side.
                if set(supports) & set(counters):
                    raise ValueError("memory_update_support_counter_overlap")
                if kind == "important":
                    identifier = update.get("record_id")
                    if not identifier or not update.get("reason", "").strip() or not supports:
                        raise ValueError("model_importance_requires_reason_and_evidence")
                    if not self._visible(db, identifier, audience):
                        raise ValueError("importance_target_unavailable")
                    bound = {r[0] for r in db.execute("SELECT source FROM pm_evidence WHERE id=?", (identifier,))} | {identifier}
                    if not set(supports).issubset(bound):
                        raise ValueError("importance_evidence_not_bound_to_record")
                    db.execute("UPDATE pm_records SET important=1 WHERE id=?", (identifier,))
                    db.execute("UPDATE pm_postings SET priority=(SELECT pinned+important FROM pm_records WHERE id=?) WHERE id=?", (identifier, identifier))
                    db.execute("INSERT OR REPLACE INTO pm_retention VALUES(?,?,?)", (identifier, update["reason"], _json(supports)))
                    continue
                if kind not in {"self_report", "interpretation"}:
                    raise ValueError("unsupported_production_memory_update")
                if not supports:
                    raise ValueError("memory_update_requires_support")
                scopes = [{r[0] for r in db.execute("SELECT audience FROM pm_visibility WHERE id=?", (ref,))} for ref in supports + counters]
                visibility = sorted(set.intersection(*scopes))
                topic = update.get("topic") or "self_report"
                context = update.get("context", "")
                identifier = update.get("record_id") or "belief_" + _hash([subject_id, topic, context, kind, visibility])[:32]
                old = db.execute("SELECT revision FROM pm_records WHERE id=?", (identifier,)).fetchone()
                if old and not self._visible(db, identifier, audience):
                    raise ValueError("belief_update_outside_audience")
                if old and kind == "interpretation":
                    prior = BeliefRevision.model_validate_json(db.execute("SELECT payload FROM pm_revisions WHERE id=? AND revision=?",
                                                                        (identifier, old[0])).fetchone()[0])
                    supports = tuple(sorted((set(prior.supporting_ids) | set(supports)) - set(counters)))
                    counters = tuple(sorted((set(prior.counter_ids) | set(counters)) - set(supports)))
                revision = BeliefRevision(record_id=identifier, subject_id=subject_id, topic=topic, context=context,
                    statement=update["statement"], kind=kind, revision=old[0] + 1 if old else 1,
                    supporting_ids=supports, counter_ids=counters, valid_from=moment,
                    supersedes=tuple(update.get("supersedes", [])))
                self._revise(db, revision, event_id + ":revision:" + str(index))
            return True

    def revise(self, revision, *, event_id):
        revision = BeliefRevision.model_validate(revision)
        with closing(self._connect()) as db, db:
            db.execute("BEGIN IMMEDIATE")
            return self._revise(db, revision, event_id)

    def _revise(self, db, revision, event_id):
        raw = revision.model_dump(mode="json")
        if not self._receipt(db, event_id, "revise", raw):
            return False
        old = db.execute("SELECT * FROM pm_records WHERE id=?", (revision.record_id,)).fetchone()
        if revision.revision != (old["revision"] + 1 if old else 1):
            raise ValueError("belief_revision_conflict")
        if old and (old["kind"] != "belief" or old["subject"] != revision.subject_id):
            raise ValueError("belief_identity_changed")
        if old:
            previous = BeliefRevision.model_validate_json(db.execute("SELECT payload FROM pm_revisions WHERE id=? AND revision=?",
                                                                    (revision.record_id, old["revision"])).fetchone()[0])
            if (previous.topic, previous.context) != (revision.topic, revision.context):
                raise ValueError("belief_facet_identity_changed")
        evidence = []
        for ref in revision.supporting_ids + revision.counter_ids:
            source = db.execute("SELECT payload,revoked FROM pm_sources WHERE id=?", (ref,)).fetchone()
            if source is None or source["revoked"]:
                raise ValueError("belief_source_unavailable")
            incomplete = db.execute("SELECT 1 FROM pm_legacy_valid WHERE id=? AND complete=0", (ref,)).fetchone()
            if incomplete:
                raise ValueError("belief_legacy_source_unverified")
            if db.execute("SELECT 1 FROM pm_legacy_presence WHERE id=? AND present=0", (ref,)).fetchone():
                raise ValueError("belief_source_unavailable")
            item = self._effective_source(db, source["payload"])
            if item.kind == "self_expression":
                raise ValueError("self_expression_cannot_prove_external_belief")
            if revision.kind == "self_report" and item.author_id != revision.subject_id:
                raise ValueError("self_report_author_mismatch")
            authority = item.original.get("record", {}).get("authority")
            if revision.kind == "self_report" and authority is not None and authority != "speaker_utterance":
                raise ValueError("self_report_requires_authored_utterance")
            if revision.kind == "interpretation" and item.author_id != revision.subject_id:
                raise ValueError("interpretation_requires_subject_observation")
            evidence.append(item)
        visibility = set.intersection(*(set(item.scope.visibility) for item in evidence))
        if not visibility:
            raise ValueError("belief_has_no_common_audience")
        # Numeric estimate is evidence support, never a relationship reward.
        support, counter = set(), set()
        for item in evidence:
            keys = ({row[0] for row in db.execute("""SELECT i.key FROM pm_lineage l
                JOIN pm_source_identity i ON i.id=l.parent WHERE l.child=?""", (item.record_id,))}
                    if item.kind == "legacy_episode" else {item.independent_key})
            (support if item.record_id in revision.supporting_ids else counter).update(keys)
        if support & counter:
            raise ValueError("same_experience_cannot_support_and_contradict")
        confidence = (len(support) + 1) / (len(support | counter) + 2)
        for identifier in revision.supersedes:
            target = db.execute("SELECT payload FROM pm_revisions WHERE id=? ORDER BY revision DESC LIMIT 1", (identifier,)).fetchone()
            if not target:
                raise ValueError("unknown_superseded_belief")
            prior = BeliefRevision.model_validate_json(target[0])
            prior_visibility = {row[0] for row in db.execute("SELECT audience FROM pm_visibility WHERE id=?", (identifier,))}
            if ((prior.subject_id, prior.topic, prior.context) != (revision.subject_id, revision.topic, revision.context)
                    or prior_visibility != visibility):
                raise ValueError("supersession_identity_or_scope_mismatch")
            db.execute("UPDATE pm_records SET active=0 WHERE id=?", (identifier,))
        db.execute("INSERT INTO pm_revisions VALUES(?,?,?)", (revision.record_id, revision.revision, _json(raw)))
        db.execute("""INSERT INTO pm_records(id,kind,subject,text,time,revision,confidence) VALUES(?,'belief',?,?,?,?,?)
            ON CONFLICT(id) DO UPDATE SET text=excluded.text,time=excluded.time,revision=excluded.revision,
                active=1,confidence=excluded.confidence""",
            (revision.record_id, revision.subject_id, revision.statement, _time(revision.valid_from), revision.revision, confidence))
        db.execute("DELETE FROM pm_evidence WHERE id=?", (revision.record_id,))
        db.execute("DELETE FROM pm_evidence_revision WHERE id=?", (revision.record_id,))
        db.executemany("INSERT INTO pm_evidence VALUES(?,?,?)", ((revision.record_id, ref, stance)
            for stance, refs in (("support", revision.supporting_ids), ("counter", revision.counter_ids)) for ref in refs))
        db.execute("""INSERT INTO pm_evidence_revision SELECT e.id,e.source,r.revision FROM pm_evidence e
            JOIN pm_records r ON r.id=e.source WHERE e.id=?""", (revision.record_id,))
        self._index(db, revision.record_id, revision.statement + " " + revision.topic, visibility)
        return True

    def retain(self, record_id, *, event_id, pinned=False, important_reason=None, evidence_ids=()):
        """Explicit pins or evidence-backed model importance keep a record reachable."""
        payload = {"id": record_id, "pinned": pinned, "reason": important_reason, "evidence": sorted(set(evidence_ids))}
        if not pinned and (not important_reason or not important_reason.strip() or not evidence_ids):
            raise ValueError("model_importance_requires_reason_and_evidence")
        with closing(self._connect()) as db, db:
            db.execute("BEGIN IMMEDIATE")
            if not self._receipt(db, event_id, "retain", payload):
                return False
            if not db.execute("SELECT 1 FROM pm_records WHERE id=? AND active=1", (record_id,)).fetchone():
                raise ValueError("retention_target_unavailable")
            allowed = {r[0] for r in db.execute("SELECT source FROM pm_evidence WHERE id=?", (record_id,))} | {record_id}
            if not set(evidence_ids).issubset(allowed):
                raise ValueError("importance_evidence_not_bound_to_record")
            db.execute("UPDATE pm_records SET pinned=MAX(pinned,?),important=MAX(important,?) WHERE id=?",
                       (int(pinned), int(bool(important_reason)), record_id))
            db.execute("UPDATE pm_postings SET priority=(SELECT pinned+important FROM pm_records WHERE id=?) WHERE id=?", (record_id, record_id))
            db.execute("INSERT OR REPLACE INTO pm_retention VALUES(?,?,?)", (record_id, important_reason or "explicit_pin", _json(payload)))
            return True

    def record_use(self, event_id, record_ids, *, audience, kind="context_exposure"):
        """Idempotent read/use audit; does not increase belief confidence."""
        if kind not in {"retrieval_hit", "context_exposure", "decision_use"}:
            raise ValueError("invalid_memory_use_kind")
        payload = {"ids": sorted(set(record_ids)), "audience": audience}
        with closing(self._connect()) as db, db:
            db.execute("BEGIN IMMEDIATE")
            if not self._receipt(db, event_id, kind, payload):
                return False
            for identifier in payload["ids"]:
                if not self._visible(db, identifier, audience):
                    raise ValueError("memory_use_outside_audience")
            return True

    @classmethod
    def _visible(cls, db, identifier, audience, *, now=None):
        indexed = db.execute("""SELECT r.kind FROM pm_records r JOIN pm_visibility v ON v.id=r.id
            WHERE r.id=? AND v.audience=? AND r.active=1
              AND NOT EXISTS(SELECT 1 FROM pm_sources s WHERE s.id=r.id AND s.revoked=1)
              AND NOT EXISTS(SELECT 1 FROM pm_evidence e JOIN pm_sources s ON s.id=e.source WHERE e.id=r.id AND s.revoked=1)
              AND NOT EXISTS(SELECT 1 FROM pm_legacy_presence p WHERE p.id=r.id AND p.present=0)
              AND NOT EXISTS(SELECT 1 FROM pm_legacy_valid l WHERE l.id=r.id AND l.complete=0)
              AND NOT EXISTS(SELECT 1 FROM pm_evidence e JOIN pm_legacy_valid l ON l.id=e.source WHERE e.id=r.id AND l.complete=0)""",
            (identifier, audience)).fetchone()
        if not indexed or not cls._evidence_versions_current(db, identifier):
            return False
        if indexed["kind"] == "claim_v2":
            from harness.memory.evidence_v2 import is_visible
            return is_visible(db, identifier, audience, now=now)
        # Indexed scope only narrows candidates. Immutable evidence is the final
        # authority, including after stale/corrupt projection or cache recovery.
        sources = db.execute("""SELECT payload,digest FROM pm_sources WHERE id=? OR id IN
            (SELECT source FROM pm_evidence WHERE id=?)""", (identifier, identifier)).fetchall()
        if not sources:
            return False
        for source in sources:
            raw = json.loads(source["payload"])
            if _hash(raw) != source["digest"]:
                raise ValueError("production_memory_source_integrity_failure")
            evidence = cls._effective_source(db, source["payload"])
            if audience not in evidence.scope.visibility:
                return False
        return True

    def retract_source(self, source_id, *, event_id, reason):
        """Immediate tombstone; all supported conclusions fail closed on every read."""
        with closing(self._connect()) as db, db:
            db.execute("BEGIN IMMEDIATE")
            identifier = source_id
            if not db.execute("SELECT 1 FROM pm_sources WHERE id=?", (identifier,)).fetchone():
                originals = db.execute("""SELECT o.id,i.key FROM pm_source_original o
                    JOIN pm_source_identity i ON i.id=o.id WHERE o.ref=?""", (source_id,)).fetchall()
                if not originals:
                    raise ValueError("unknown_retracted_source")
                if len({row["key"] for row in originals}) != 1:
                    raise ValueError("ambiguous_retracted_source")
                identifier = originals[0]["id"]
            if not self._receipt(db, event_id, "retract", {"id": source_id, "reason": reason}):
                return False
            kind = db.execute("SELECT json_extract(payload,'$.kind') FROM pm_sources WHERE id=?", (identifier,)).fetchone()[0]
            duplicates = ([identifier] if kind == "legacy_episode" else [row[0] for row in db.execute("""SELECT i.id
                FROM pm_source_identity i JOIN pm_sources s ON s.id=i.id WHERE i.key IN
                (SELECT key FROM pm_source_identity WHERE id=?) AND json_extract(s.payload,'$.kind')<>'legacy_episode'""",
                (identifier,))] or [identifier])
            self._deactivate_source_tree(db, duplicates)
            return True

    def delete_source(self, source_id, *, event_id, reason="explicit deletion"):
        """Logically delete a source and its derived reads without rewriting it.

        The immutable archive remains owner-auditable; a legal hard-erasure
        policy needs a separate archive retention operation.
        """
        return self.retract_source(source_id, event_id=event_id, reason=reason)

    def validate_references(self, references, *, audience, now=None):
        """Commit fence; dictionaries may freeze ``record_id`` and ``revision``."""
        moment = _time(now)
        with closing(self._connect()) as db:
            for reference in references:
                identifier = reference if isinstance(reference, str) else reference.get("record_id")
                if not identifier or not self._visible(db, identifier, audience, now=now):
                    return False
                row = db.execute("SELECT kind,revision FROM pm_records WHERE id=?", (identifier,)).fetchone()
                if isinstance(reference, dict) and reference.get("revision", row["revision"]) != row["revision"]:
                    return False
                if row["kind"] == "belief":
                    claim = BeliefRevision.model_validate_json(db.execute("SELECT payload FROM pm_revisions WHERE id=? AND revision=?",
                                                                         (identifier, row["revision"])).fetchone()[0])
                    if _time(claim.valid_from) > moment or (claim.valid_until and _time(claim.valid_until) <= moment):
                        return False
            return True

    def recall(self, *, audience, query=None, subject_ids=(), limit=8, max_characters=6000, now=None, diagnostics=None, event_id=None):
        """SQL candidates are bounded before JSON decoding; audience is never inferred."""
        if not 1 <= limit <= 100 or not 256 <= max_characters <= 100000:
            raise ValueError("invalid_memory_recall_budget")
        moment = _time(now)
        terms = _terms((query or "")[:512])[:32]
        subject_ids = tuple(dict.fromkeys(subject_ids))[:32]
        if subject_ids:
            from harness.memory.identity import IdentityStore
            subject_ids = IdentityStore(self).aliases(subject_ids)
        candidates = set()
        with closing(self._connect()) as db:
            base = "SELECT r.id FROM pm_records r JOIN pm_visibility v ON v.id=r.id WHERE v.audience=? AND r.active=1"
            if terms:
                per_term = max(1, 128 // len(terms))
                for term in terms:
                    candidates.update(r[0] for r in db.execute("""SELECT p.id FROM pm_postings p JOIN pm_records r ON r.id=p.id
                        WHERE p.audience=? AND p.term=? AND r.active=1
                        ORDER BY p.priority DESC,p.time DESC,p.id LIMIT ?""", (audience, term, per_term)))
            if subject_ids:
                candidates.update(r[0] for r in db.execute(base + " AND r.subject IN (" + ",".join("?" for _ in subject_ids) +
                    ") ORDER BY r.important DESC,r.pinned DESC,r.time DESC LIMIT 64", (audience, *subject_ids)))
            if not candidates:
                candidates.update(r[0] for r in db.execute(base + " ORDER BY r.pinned DESC,r.important DESC,r.time DESC LIMIT 64", (audience,)))
            rows = []
            if diagnostics is not None:
                diagnostics.update(candidate_count=len(candidates), candidate_limit=192, query_terms=len(terms))
            for identifier in sorted(candidates):
                if not self._visible(db, identifier, audience, now=now):
                    continue
                row = db.execute("SELECT * FROM pm_records WHERE id=?", (identifier,)).fetchone()
                if row["kind"] == "experience":
                    source = self._effective_source(db, db.execute("SELECT payload FROM pm_sources WHERE id=?", (identifier,)).fetchone()[0])
                    entry = {"record_id": identifier, "kind": "episode", "summary": source.text,
                        "authority": "legacy_derived_episode" if source.kind == "legacy_episode" else "source_attributed_experience",
                        "source_refs": list(source.source_refs),
                        "subject_refs": [source.author_id], "source_channel": source.scope.channel,
                        "source_conversation_id": source.scope.conversation_id, "occurred_at": _time(source.occurred_at), "revision": row["revision"]}
                elif row["kind"] == "claim_v2":
                    from harness.memory.evidence_v2 import project_entry
                    entry = project_entry(db, identifier, audience, now=now)
                    if entry is None:
                        continue
                else:
                    claim = BeliefRevision.model_validate_json(db.execute("SELECT payload FROM pm_revisions WHERE id=? AND revision=?", (identifier, row["revision"])).fetchone()[0])
                    if _time(claim.valid_from) > moment or (claim.valid_until and _time(claim.valid_until) <= moment):
                        continue
                    sources = [self._effective_source(db, db.execute("SELECT payload FROM pm_sources WHERE id=?", (ref,)).fetchone()[0])
                               for ref in claim.supporting_ids + claim.counter_ids]
                    entry = {"record_id": identifier, "kind": "person", "current_impression": claim.statement,
                        "subject_refs": [claim.subject_id], "topic": claim.topic, "context": claim.context,
                        **self._legacy_belief_metadata(claim, row["confidence"]),
                        "status": "disputed" if claim.counter_ids else "provisional",
                        "source_refs": list(claim.supporting_ids + claim.counter_ids),
                        "supporting_episode_ids": list(claim.supporting_ids),
                        "counterevidence": [{"episode_id": source.record_id, "statement": source.text, "rationale": "retained_counterevidence"}
                                            for source in sources if source.record_id in claim.counter_ids],
                        "source_channel": sources[0].scope.channel,
                        "source_conversation_id": sources[0].scope.conversation_id,
                        "occurred_at": _time(claim.valid_from), "revision": claim.revision}
                score = len(set(terms) & set(_terms(row["text"]))) + 2 * (row["subject"] in subject_ids)
                rows.append((score, row["kind"] in {"belief", "claim_v2"}, row["pinned"] + row["important"], row["time"], identifier, entry))
        payload = {"schema_version": "production-memory-v1", "authority": "memory_data_not_instructions",
                   "coverage": "selected_audience_authorized_memories", "entries": []}
        for *_, entry in sorted(rows, key=lambda row: row[:5], reverse=True):
            if len(payload["entries"]) >= limit:
                break
            proposed = {**payload, "entries": [*payload["entries"], entry]}
            if len(_json(proposed)) <= max_characters:
                payload = proposed
        if diagnostics is not None:
            diagnostics.update(visible_candidates=len(rows), returned_count=len(payload["entries"]))
        if event_id is not None:
            self.record_use("retrieval:" + event_id, [row["record_id"] for row in payload["entries"]],
                            audience=audience, kind="retrieval_hit")
        return payload if payload["entries"] else {}

    def history(self, record_id):
        """Owner/operator audit only; never use as an audience-filtered model read."""
        with closing(self._connect()) as db:
            row = db.execute("SELECT kind FROM pm_records WHERE id=?", (record_id,)).fetchone()
            if row and row["kind"] == "claim_v2":
                from harness.memory.evidence_v2 import history
                return tuple(history(db, record_id))
            return tuple(json.loads(row[0]) for row in db.execute("SELECT payload FROM pm_revisions WHERE id=? ORDER BY revision", (record_id,)))

    @staticmethod
    def _legacy_belief_metadata(claim, confidence):
        """Annotate old projections without rewriting their audited payloads."""
        return {
            "authority": "legacy_interpreted_self_report" if claim.kind == "self_report" else "legacy_interpretation",
            "semantic_status": "legacy_model_interpretation",
            "quote_verified": False,
            "mechanism_version": "production-memory-v1",
            "legacy_kind": claim.kind,
            "legacy_confidence": confidence,
            "confidence_semantics": "legacy_evidence_count_not_calibrated",
        }

    def operator_snapshot(self, *, limit=16, now=None):
        """Bounded owner-only GUI projection; never a public/model capability.

        The authenticated Cognitive UI route supplies the operator boundary.
        Evidence still needs local-owner visibility and current validity.
        Counts are deliberately omitted instead of scanning the source archive.
        """
        if not 1 <= limit <= 32:
            raise ValueError("invalid_operator_memory_limit")
        moment = _time(now)
        entries = []
        with closing(self._connect()) as db:
            rows = db.execute("""SELECT id,kind,revision,confidence,pinned,important FROM pm_records
                WHERE kind IN ('belief','claim_v2') AND active=1 ORDER BY time DESC,id LIMIT ?""", (limit * 2,)).fetchall()
            for row in rows:
                if not self._visible(db, row["id"], "local:main", now=now):
                    continue
                if row["kind"] == "claim_v2":
                    from harness.memory.evidence_v2 import operator_entry
                    entry = operator_entry(db, row["id"], audience="local:main", now=now)
                    if entry is not None:
                        retention = db.execute("SELECT reason FROM pm_retention WHERE id=?", (row["id"],)).fetchone()
                        entries.append({**entry, "pinned": bool(row["pinned"]), "important": bool(row["important"]),
                                        "important_reason": retention["reason"] if retention else None})
                    if len(entries) >= limit:
                        break
                    continue
                claim = BeliefRevision.model_validate_json(db.execute(
                    "SELECT payload FROM pm_revisions WHERE id=? AND revision=?", (row["id"], row["revision"])).fetchone()[0])
                if _time(claim.valid_from) > moment or (claim.valid_until and _time(claim.valid_until) <= moment):
                    continue
                evidence = []
                # Full evidence identity is retained; the GUI shows a bounded
                # subset of originals, with an explicit omitted count.
                refs = tuple(dict.fromkeys(claim.counter_ids + claim.supporting_ids))
                for ref in refs[:8]:
                    source = self._effective_source(db, db.execute("SELECT payload FROM pm_sources WHERE id=?", (ref,)).fetchone()[0])
                    evidence.append({"record_id": ref, "stance": "counter" if ref in claim.counter_ids else "support",
                        "text": source.text, "author_id": source.author_id, "occurred_at": _time(source.occurred_at),
                        "scope": source.scope.model_dump(mode="json"), "source_refs": list(source.source_refs)})
                retention = db.execute("SELECT reason,evidence FROM pm_retention WHERE id=?", (row["id"],)).fetchone()
                entries.append({"record_id": row["id"], "revision": row["revision"], "subject_id": claim.subject_id,
                    "topic": claim.topic, "context": claim.context, "statement": claim.statement, "kind": claim.kind,
                    **self._legacy_belief_metadata(claim, row["confidence"]),
                    "pinned": bool(row["pinned"]), "important": bool(row["important"]),
                    "important_reason": retention["reason"] if retention else None,
                    "valid_from": _time(claim.valid_from), "valid_until": _time(claim.valid_until) if claim.valid_until else None,
                    "evidence": evidence, "omitted_evidence_count": max(0, len(refs) - len(evidence))})
                if len(entries) >= limit:
                    break
            cursors = [dict(row) for row in db.execute("SELECT stream,cursor FROM pm_cursors ORDER BY stream LIMIT 32")]
            evidence_tasks = [dict(row) for row in db.execute("""SELECT task_id,group_id,reason,created_at,status
                FROM pm_v2_tasks WHERE audience='local:main' AND status='pending'
                ORDER BY created_at,task_id LIMIT 32""")]
        return {"schema_version": "production-memory-operator-v1", "owner_id": self.owner_id,
            "preset_id": self.preset_id, "authority": "operator_only", "entries": entries,
            "coverage": "bounded_current_person_understandings", "limit": limit, "ingestion_cursors": cursors,
            "evidence_tasks": evidence_tasks, "evidence_task_scope": "local:main"}

    def _bind_daily_source_aliases(self, db, state):
        """Resolve frozen daily evidence identities by their authenticated raw hash.

        A lexical resemblance to an ID never establishes lineage. Historical
        ledgers without matching originals remain readable history only.
        """
        from harness.memory.revision.sources import FrozenSource
        for identifier, raw in state.get("sources", {}).items():
            try:
                frozen = FrozenSource.model_validate(raw)
            except (ValueError, TypeError):
                continue
            if (identifier != frozen.source_id or frozen.owner_id != self.owner_id
                    or frozen.preset_id != self.preset_id):
                continue
            row = db.execute("SELECT payload FROM pm_sources WHERE id=?", (identifier,)).fetchone()
            if row is None:
                continue
            source = Experience.model_validate_json(row[0])
            record = source.original.get("record", {})
            if (source.kind == "legacy_episode" or not record or "source" not in source.original
                    or _hash(source.original["source"]) != frozen.source_hash
                    or source.author_id != frozen.author_principal or source.scope != frozen.scope
                    or source.occurred_at != frozen.occurred_at
                    or record.get("text") != frozen.text or record.get("kind") != frozen.kind
                    or source.source_refs != frozen.source_refs):
                continue
            for alias in frozen.evidence_keys:
                db.execute("INSERT OR IGNORE INTO pm_source_original VALUES(?,?)", (alias, identifier))
                for legacy in db.execute("SELECT id FROM pm_legacy_dependencies WHERE ref=?", (alias,)).fetchall():
                    self._refresh_legacy_lineage(db, legacy[0])

    def import_legacy(self, preset):
        """Offline/background compatibility projection, without any model calls.

        Every original version and identifier is retained. Source experiences
        stay immutable; subsequent interpretation changes create new revisions.
        This method is intentionally not run on every foreground retrieval.
        """
        if preset.preset_id != self.preset_id:
            raise ValueError("legacy_preset_identity_mismatch")
        changed = 0
        with closing(self._connect()) as db, db:
            db.execute("BEGIN IMMEDIATE")
            def archive(identifier, raw):
                nonlocal changed
                digest = _hash(raw)
                db.execute("INSERT OR IGNORE INTO pm_legacy_versions VALUES(?,?,?)", (identifier, digest, _json(raw)))
                old = db.execute("SELECT digest FROM pm_legacy WHERE id=?", (identifier,)).fetchone()
                if old and old[0] == digest:
                    return False
                db.execute("INSERT OR REPLACE INTO pm_legacy VALUES(?,?,?)", (identifier, digest, _json(raw)))
                changed += 1
                return True

            # Keep identity, original daily source ledgers and historical
            # interpretation receipts byte-for-byte at the JSON value level.
            # Unmapped history is auditable but cannot authorize current recall.
            prefix = "legacy-state:" + preset.preset_id + ":"
            archive(prefix + "identity", preset.model_dump(mode="json", exclude={
                "episodic", "semantic", "candidates", "relationships", "qq_memory_state", "daily_revision_state"}))
            archive(prefix + "qq_memory", preset.qq_memory_state)
            archive(prefix + "daily_revision", preset.daily_revision_state)
            self._bind_daily_source_aliases(db, preset.daily_revision_state)

            # Full authoritative snapshots also carry removals and rollback.
            # Historical payloads remain archived, but no absent interpretation
            # can authorize a new read or a dependent belief.
            current_ids = {event.event_id for event in preset.episodic
                           if event.revision_metadata.get("status") not in {"retracted", "superseded", "invalidated", "dropped"}}
            current_ids.update(fact.fact_id for fact in preset.semantic
                               if fact.revision_metadata.get("status") not in {"retracted", "superseded", "invalidated", "dropped"})
            current_ids.update(preset.qq_memory_state.get("impressions", {}))
            db.execute("""INSERT OR IGNORE INTO pm_legacy_presence SELECT l.id,1 FROM pm_legacy l
                JOIN pm_records r ON r.id=l.id""")
            previous_presence = dict(db.execute("SELECT id,present FROM pm_legacy_presence"))
            restored = {identifier for identifier in current_ids if previous_presence.get(identifier) == 0}
            removed = {identifier for identifier, present in previous_presence.items() if present and identifier not in current_ids}
            db.executemany("UPDATE pm_legacy_presence SET present=0 WHERE id=?", ((identifier,) for identifier in removed))
            db.executemany("UPDATE pm_records SET active=0 WHERE id=?", ((identifier,) for identifier in removed))
            db.executemany("INSERT INTO pm_legacy_presence VALUES(?,1) ON CONFLICT(id) DO UPDATE SET present=1",
                           ((identifier,) for identifier in current_ids))
            changed += len(removed)

            for event in preset.episodic:
                raw = event.model_dump(mode="json")
                prior = db.execute("SELECT payload FROM pm_legacy WHERE id=?", (event.event_id,)).fetchone()
                archived = archive(event.event_id, raw)
                if not archived and event.event_id not in restored:
                    continue
                previous_source = db.execute("SELECT payload FROM pm_sources WHERE id=?", (event.event_id,)).fetchone()
                if previous_source and Experience.model_validate_json(previous_source[0]).kind != "legacy_episode":
                    raise ValueError("legacy_record_identity_collision")
                if not previous_source:
                    participants = [p for p in event.participants if p not in {"character", "character:misty"}]
                    self._ingest(db, Experience(record_id=event.event_id,
                        author_id=participants[0] if len(participants) == 1 else "legacy:unattributed",
                        text=event.objective_fact or event.summary, occurred_at=event.time,
                        scope=event.scope or MemoryScope(channel=event.channel, conversation_id=event.session_id),
                        source_refs=tuple(event.source_refs),
                        independent_key="legacy-projection:" + event.event_id,
                        kind="legacy_episode", original=raw))
                # Keep immutable first versions in pm_sources. The current
                # derived view, its lineage, and its version follow the ledger.
                fields = ("summary", "objective_fact", "source_refs", "evidence", "scope", "participants", "time")
                previous_raw = json.loads(prior[0]) if prior else {}
                if event.event_id in restored or any(previous_raw.get(key) != raw.get(key) for key in fields):
                    db.execute("UPDATE pm_records SET revision=revision+1,text=?,time=? WHERE id=?",
                               (event.objective_fact or event.summary, _time(event.time), event.event_id))
                    db.execute("DELETE FROM pm_legacy_dependencies WHERE id=?", (event.event_id,))
                    db.executemany("INSERT OR IGNORE INTO pm_legacy_dependencies VALUES(?,?)",
                                   ((event.event_id, ref) for ref in event.source_refs))
                    self._refresh_legacy_lineage(db, event.event_id)
                    scope = event.scope or MemoryScope(channel=event.channel, conversation_id=event.session_id)
                    self._index(db, event.event_id, event.objective_fact or event.summary, scope.visibility)
                # Forgetting concerns accessibility, not rewriting historical facts.
                db.execute("UPDATE pm_records SET active=(? AND (? OR pinned=1 OR important=1)) WHERE id=?",
                           (int(event.event_id in current_ids), int(event.tier != "forgotten"), event.event_id))
                if event.event_id not in current_ids:
                    db.execute("INSERT OR REPLACE INTO pm_legacy_presence VALUES(?,0)", (event.event_id,))

            interpretations = []
            for raw in preset.qq_memory_state.get("impressions", {}).values():
                refs = tuple(dict.fromkeys(e["episode_id"] for e in raw.get("evidence", []) if e.get("stance") == "support"))
                counters = tuple(dict.fromkeys(e["episode_id"] for e in raw.get("evidence", []) if e.get("stance") == "contradict"))
                interpretations.append((raw["impression_id"], raw, raw.get("subject_refs", []), raw.get("topic") or raw["kind"],
                    raw.get("context", ""), raw["current_impression"], refs, counters,
                    raw.get("updated_at") or raw["first_observed_at"], raw.get("status") not in {"dormant", "forgotten"}))
            for fact in preset.semantic:
                raw = fact.model_dump(mode="json")
                # Existing impression projections are archived, not duplicated in recall.
                if fact.fact_id.startswith("qqsemantic_"):
                    archive(fact.fact_id, raw)
                    continue
                interpretations.append((fact.fact_id, raw, [fact.subject], fact.predicate, "", fact.value,
                    tuple(fact.supporting_events), (), fact.formed_at,
                    fact.revision_metadata.get("status") not in {"superseded", "retracted", "invalidated"}))
            for candidate in preset.candidates:
                archive(candidate.candidate_id, candidate.model_dump(mode="json"))
            for relation in preset.relationships:
                archive(relation.relation_id, relation.model_dump(mode="json"))
            for identifier, raw, subjects, topic, context, statement, supports, counters, at, active in interpretations:
                archived = archive(identifier, raw)
                existing = db.execute("SELECT revision FROM pm_records WHERE id=?", (identifier,)).fetchone()
                if (not archived and existing and identifier not in restored
                        and self._evidence_versions_current(db, identifier)):
                    continue
                available = {row[0] for row in db.execute("""SELECT s.id FROM pm_sources s WHERE s.revoked=0
                    AND NOT EXISTS(SELECT 1 FROM pm_legacy_valid l WHERE l.id=s.id AND l.complete=0)
                    AND NOT EXISTS(SELECT 1 FROM pm_legacy_presence p WHERE p.id=s.id AND p.present=0) AND s.id IN (""" +
                    ",".join("?" for _ in supports + counters) + ")", supports + counters)} if supports or counters else set()
                # Missing provenance is archived, never replaced with invented evidence.
                if len(available) != len(set(supports + counters)) or not available:
                    continue
                rev = BeliefRevision(record_id=identifier,
                    subject_id=subjects[0] if len(subjects) == 1 else "legacy:subjects:" + _hash(sorted(subjects))[:24],
                    topic=topic, context=context, statement=statement, kind="legacy_interpretation",
                    revision=existing[0] + 1 if existing else 1, supporting_ids=supports, counter_ids=counters,
                    valid_from=at, original=raw)
                self._revise(db, rev, "legacy:" + identifier + ":" + _hash(raw) + ":" + str(rev.revision))
                if not active:
                    db.execute("UPDATE pm_records SET active=0 WHERE id=?", (identifier,))
        return changed

    def legacy_history(self, record_id):
        with closing(self._connect()) as db:
            return tuple(json.loads(row[0]) for row in db.execute("SELECT payload FROM pm_legacy_versions WHERE id=? ORDER BY rowid", (record_id,)))
